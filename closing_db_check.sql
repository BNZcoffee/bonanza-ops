  select 'FUNCTION' kind, name obj,
    exists(select 1 from pg_proc p join pg_namespace n on n.oid=p.pronamespace
           where n.nspname='public' and p.proname=name) ok
  from expected_funcs
),
ccheck as (
  select 'COLUMN' kind, tbl||'.'||col obj,
    exists(select 1 from information_schema.columns
           where table_schema='public' and table_name=tbl and column_name=col) ok
  from expected_cols
),
typecheck as (
  select 'TYPE' kind, 'users.id = uuid' obj,
    exists(select 1 from information_schema.columns
           where table_schema='public' and table_name='users' and column_name='id' and data_type='uuid') ok
)
